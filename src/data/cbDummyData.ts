// Helper to extract dynamic unique filter options from any store list
export const extractUniqueOptions = (stores: CBStoreRecord[]) => {
  return {
    gms: Array.from(new Set(stores.map((s) => s.gm))).filter(Boolean).sort(),
    ams: Array.from(new Set(stores.map((s) => s.am))).filter(Boolean).sort(),
    territories: Array.from(new Set(stores.map((s) => s.territory))).filter(Boolean).sort(),
    provinces: Array.from(new Set(stores.map((s) => s.province))).filter(Boolean).sort(),
    cities: Array.from(new Set(stores.map((s) => s.city))).filter(Boolean).sort(),
    storeStatuses: Array.from(new Set(stores.map((s) => s.storeStatus))).filter(Boolean).sort(),
    statuses: ['Overstaffed', 'Understaffed', 'Optimal'],
    sizes: Array.from(new Set(stores.map((s) => String(s.size)))).filter(Boolean).sort(),
  };
};

